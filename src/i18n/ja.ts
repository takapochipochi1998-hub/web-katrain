const tag = (word: string): string => exact[word] ?? word;

const patterns: Dictionary['patterns'] = [
  // Bot style tags such as "Calm · Balanced".
  [/^([A-Z][a-z]+) · ([A-Z][a-z]+)$/, (_m, a, b) => `${tag(a!)} · ${tag(b!)}`],
  [/^Move (\d+) of (\d+), (Black|White) (\S+)$/, (_m, n, total, color, at) => `${n}手目 / 全${total}手、${color === 'Black' ? '黒' : '白'} ${at}`],
  [/^Move (\d+): ([BW]) (\S+)\nAnalysis off/, (_m, n, c, at) => `${n}手目: ${c === 'B' ? '黒' : '白'} ${at}\n解析オフ`],
  [/^Plays like an? (.+) player, from KataGo's human network\.$/, (_m, rank) => `KataGoの人間模倣モデルで、${rankJa(rank!)}の人のように打ちます。`],
  [/^(\d+) (kyu|dan) \(pre-AlphaGo style\)$/, (_m, n, u) => `${n}${u === 'kyu' ? '級' : '段'}（AlphaGo以前の打ち方）`],
  [/^Pro, (\d{4})$/, 'プロ（$1年ごろ）'],
  [/(\d+) moves · /, '$1手 · '],
  [/^(\d+) games · (\d+) folders? · (.+)$/, '$1局 · $2フォルダ · $3'],
  [/^Move (\d+) of (\d+)$/, '$1手目 / 全$2手'],
  [/^Move (\d+)$/, '$1手目'],
  [/^(\d+) kyu$/, '$1級'],
  [/^(\d+) dan$/, '$1段'],
  [/^(\d+) pro$/, 'プロ$1段'],
  [/^Ready · (.+)$/, '準備完了 · $1'],
  [/^Black \+([\d.]+)$/, '黒 +$1目'],
  [/^White \+([\d.]+)$/, '白 +$1目'],
  [/^(\d+) moves$/, '$1手'],
];

function rankJa(rank: string): string {
  const m = /^(\d+) (kyu|dan)$/.exec(rank);
  return m ? `${m[1]}${m[2] === 'kyu' ? '級' : '段'}` : rank;
}

